import { JSDOM } from 'jsdom';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const html=await readFile('dist/lap-trinh/jwt/index.html','utf8');
const d=new JSDOM(html).window.document;
assert.equal(d.querySelectorAll('h1').length,1);
assert.equal(d.querySelector('h1').textContent,'JWT');
assert.equal(d.querySelectorAll('.jwt-part').length,3);
assert.deepEqual([...d.querySelectorAll('.jwt-part h3')].map(e=>e.textContent),['Header','Payload','Signature']);
assert.equal(d.querySelectorAll('.jwt-claim-tags span').length,3);
assert.equal(d.querySelectorAll('.jwt-lane-boxes rect').length,3);
assert.equal(d.querySelectorAll('.jwt-flow-requests path,.jwt-flow-responses path').length,4);
assert.equal(d.querySelector('.jwt-flow-scroll').tabIndex,0);
assert.ok(d.querySelector('svg[role="img"] title'));
assert.ok(d.querySelector('svg[role="img"] desc'));
const codes=[...d.querySelectorAll('pre code')].map(e=>JSON.parse(e.textContent));
assert.deepEqual(codes[0],{typ:'JWT',alg:'HS256'});
assert.deepEqual(Object.keys(codes[1]),['sub','name','iss','aud','exp']);
assert.equal(codes[1].sub,'user-123');
assert.equal(codes[1].iss,'auth.example');
assert.equal(typeof codes[1].exp,'number');
assert.match(d.querySelector('.jwt-frame-note').textContent,/không phải mã hóa bảo mật/);
assert.match(d.querySelector('.jwt-key-note').textContent,/khóa công khai/);
assert.match(d.querySelector('.jwt-remember').textContent,/iss.*aud.*exp.*nbf/);
assert.match(d.querySelector('.jwt-sources').textContent,/JWE/);
assert.equal(d.querySelectorAll('.jwt-sources a').length,3);
assert.equal(d.querySelectorAll('.jwt-poster img').length,0);
const ids=[...d.querySelectorAll('[id]')].map(e=>e.id);assert.equal(new Set(ids).size,ids.length);
const css=await readFile('src/styles/jwt.css','utf8');
assert.doesNotMatch(css,/(?:^|[},\s])(?:body|\.sidebar|\.mobile-header|\.breadcrumb|\.toc|\.page-shell)\s*[.{:#]/);
assert.match(css,/@container\(max-width:560px\)/);
console.log('PASS JWT: selectable anatomy, synthetic JSON, 3 claims groups, 3-lane accessible sequence, security qualifications, sources and article-only CSS.');
